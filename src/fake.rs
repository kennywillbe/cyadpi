#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn http_fake_is_the_goodbyedpi_string() {
        assert_eq!(
            FAKE_HTTP,
            &b"GET / HTTP/1.1\r\nHost: www.w3.org\r\nUser-Agent: curl/7.65.3\r\nAccept: */*\r\nAccept-Encoding: deflate, gzip, br\r\n\r\n"[..]
        );
        assert_eq!(FAKE_HTTP.len(), 110); // sizeof - 1 in the C source
    }

    #[test]
    fn https_fake_is_a_client_hello_for_w3() {
        let p = &FAKE_HTTPS;
        // Record length field covers the rest of the buffer.
        assert_eq!(usize::from(u16::from_be_bytes([p[3], p[4]])) + 5, p.len());
        let sni = b"\x00\x00\x00\x0f\x00\x0d\x00\x00\x0awww.w3.org";
        assert!(p.windows(sni.len()).any(|w| w == sni));
        assert_eq!(
            &p[..11],
            &[
                0x16, 0x03, 0x01, 0x02, 0x00, 0x01, 0x00, 0x01, 0xfc, 0x03, 0x03
            ]
        );
        assert_eq!(&p[p.len() - 4..], &[0, 0, 0, 0]);
    }

    #[test]
    fn https_fake_matches_upstream_digest() {
        // FNV-1a over the 517 bytes, computed from the upstream C array; a
        // cheap guard against a byte getting lost in an edit.
        let mut h: u64 = 0xcbf2_9ce4_8422_2325;
        for b in FAKE_HTTPS {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0100_0000_01b3);
        }
        assert_eq!(h, 0xd2cc_1a67_5514_e97d);
    }
}
